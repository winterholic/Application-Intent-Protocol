use tokio_postgres::NoTls;

const SPEC: &str = r#"
resource Member {
  fields { id: Id; name: Text }
}
actor Member

resource SecretItem {
  fields {
    id: Id
    owner: Member
    title: Text
    secret_body: Text encrypted(scope: service)
    secret_tag: Text encrypted(scope: service, lookup: eq)
  }
  rows read when owner = actor
  transition update_title {
    allow owner = actor
    from title != "updated"
    to title = "updated"
  }
  expose create { allow true; fields owner, title, secret_body, secret_tag }
  expose read {
    select id, title, secret_body, secret_tag
    filter secret_tag.eq
    sort id
    budget { rows 100; depth 1; deadline 2s; cost 100 }
  }
  expose apply update_title { target id; bulk maxRows 10 }
}
"#;

async fn test_db(schema: &str) -> (tokio_postgres::Client, tokio::task::JoinHandle<()>) {
    let dsn = aip_test_support::test_database_url!();
    let (client, connection) = tokio_postgres::connect(dsn, NoTls).await.unwrap();
    let handle = tokio::spawn(async move {
        if let Err(e) = connection.await {
            eprintln!("connection error: {e}");
        }
    });
    client.batch_execute(&format!("CREATE SCHEMA IF NOT EXISTS {schema}")).await.unwrap();
    (client, handle)
}

fn test_crypto_v1() -> Arc<RuntimeCrypto> {
    let fp_keys = FpKeys::new("fp1", vec![("fp1", [0x11; 32]), ("fp2", [0x22; 32])]).unwrap();
    let mut data_keys = BTreeMap::new();
    let dek1 = DataKey::new("dek1", 1, [0x33; 32]).unwrap();
    let dek2 = DataKey::new("dek2", 2, [0x44; 32]).unwrap();
    data_keys.insert("dek1:1".to_string(), dek1);
    data_keys.insert("dek2:2".to_string(), dek2);
    Arc::new(RuntimeCrypto { fp_keys, data_keys })
}

fn test_crypto_v2_rotated() -> Arc<RuntimeCrypto> {
    // fp2 is now active, fp1 is retained
    let fp_keys = FpKeys::new("fp2", vec![("fp1", [0x11; 32]), ("fp2", [0x22; 32])]).unwrap();
    let mut data_keys = BTreeMap::new();
    let dek1 = DataKey::new("dek1", 1, [0x33; 32]).unwrap();
    let dek2 = DataKey::new("dek2", 2, [0x44; 32]).unwrap();
    data_keys.insert("dek1:1".to_string(), dek1);
    data_keys.insert("dek2:2".to_string(), dek2);
    Arc::new(RuntimeCrypto { fp_keys, data_keys })
}

#[tokio::test]
async fn encryption_read_write_zero_plaintext_and_idempotency_rotation() {
    let schema = format!("aip_enc_test_{}", std::process::id());
    sqlgen::set_schema(&schema);
    let (mut db, conn_handle) = test_db(&schema).await;

    // Load spec facts
    let facts = load_str(SPEC, Form::A).unwrap().execution;

    // DDL
    db.batch_execute(&format!(
        "CREATE TABLE {schema}.member (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name text NOT NULL); \
         CREATE TABLE {schema}.secret_item ( \
           id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, \
           owner_id bigint NOT NULL, \
           title text NOT NULL, \
           secret_body text NOT NULL, \
           secret_tag text NOT NULL, \
           secret_tag__bidx text \
         );"
    ))
    .await
    .unwrap();

    // Prepare aip_idem and audit table
    spike_v6_transport::prepare(&db).await;
    let audit_table = format!("{schema}.aip_audit");
    spike_v3_write::set_audit_table(Some(audit_table.clone())).unwrap();
    db.batch_execute(&spike_v3_write::audit_ddl(&schema)).await.unwrap();

    // Set runtime crypto
    let crypto = test_crypto_v1();
    encryption::set_runtime_crypto(Some(crypto.clone()));

    let caller = Caller { actor_id: Some(1), now: "2026-10-19T00:00:00Z".to_string() };
    let wire = IdWire::SafeNumber;

    // Seed actor member
    db.batch_execute(&format!("INSERT INTO {schema}.member (name) VALUES ('alice')")).await.unwrap();

    // 1. /apply (create) with sensitive plaintext fields
    let plaintext_body = "super-confidential-password-xyz-98765";
    let plaintext_tag = "prod-auth-token-4321";
    let idem_key = "key-create-001";

    let create_body = json!({
        "key": idem_key,
        "request": {
            "atomic": [{
                "create": "SecretItem",
                "values": {
                    "owner": 1,
                    "title": "Production Secret",
                    "secret_body": plaintext_body,
                    "secret_tag": plaintext_tag
                }
            }]
        }
    });

    let apply_res = spike_v6_transport::handle(&mut db, &facts, "/apply", &create_body, &caller, wire).await;
    assert_eq!(apply_res["ok"], true, "apply failed: {apply_res}");
    let created_id = apply_res["created"][0]["id"].as_i64().expect("created id");
    assert!(created_id > 0, "valid created id");

    // 2. PROVE ZERO PLAINTEXT IN DATABASE TABLES
    // Check secret_item table row
    let row = db
        .query_one(&format!("SELECT secret_body, secret_tag, secret_tag__bidx FROM {schema}.secret_item WHERE id = $1"), &[&created_id])
        .await
        .unwrap();

    let db_body: String = row.get(0);
    let db_tag: String = row.get(1);
    let db_bidx: String = row.get(2);

    // Assert ciphertext frames, NOT plaintext
    assert!(db_body.starts_with("v2:"), "db_body must be v2 cell frame, got: {db_body}");
    assert!(db_tag.starts_with("v2:"), "db_tag must be v2 cell frame, got: {db_tag}");
    assert!(db_bidx.starts_with("bidx_v1:"), "db_bidx must be bidx_v1 tag, got: {db_bidx}");
    assert!(!db_body.contains(plaintext_body), "DB secret_body contains plaintext!");
    assert!(!db_tag.contains(plaintext_tag), "DB secret_tag contains plaintext!");

    // Verify whole database for plaintext leak
    let leaked_in_table = db
        .query(
            &format!("SELECT id FROM {schema}.secret_item WHERE secret_body LIKE $1 OR secret_tag LIKE $2"),
            &[&format!("%{plaintext_body}%"), &format!("%{plaintext_tag}%")],
        )
        .await
        .unwrap();
    assert!(leaked_in_table.is_empty(), "Plaintext leaked into secret_item table!");

    // 3. PROVE ZERO PLAINTEXT IN aip_idem (Idempotency storage)
    let idem_row = db.query_one(&format!("SELECT request, result::text FROM {schema}.aip_idem WHERE key = $1"), &[&idem_key]).await.unwrap();
    let stored_request: String = idem_row.get(0);
    assert!(!stored_request.contains(plaintext_body), "Plaintext body leaked into aip_idem.request!");
    assert!(!stored_request.contains(plaintext_tag), "Plaintext tag leaked into aip_idem.request!");
    assert!(stored_request.contains("$aip_enc_fp"), "aip_idem.request must contain $aip_enc_fp markers!");
    assert!(stored_request.contains("idem_v2:fp1:"), "HMAC marker must have idem_v2 format!");

    // 4. PROVE ZERO PLAINTEXT IN aip_audit (Audit snapshot)
    let audit_rows = db.query(&format!("SELECT before::text, after::text FROM {schema}.aip_audit"), &[]).await.unwrap();
    for a_row in &audit_rows {
        let before_text: String = a_row.get(0);
        let after_text: String = a_row.get(1);
        assert!(!before_text.contains(plaintext_body), "Plaintext body leaked into aip_audit.before!");
        assert!(!before_text.contains(plaintext_tag), "Plaintext tag leaked into aip_audit.before!");
        assert!(!after_text.contains(plaintext_body), "Plaintext body leaked into aip_audit.after!");
        assert!(!after_text.contains(plaintext_tag), "Plaintext tag leaked into aip_audit.after!");
    }

    // 5. /read and transparent decryption
    let read_query = json!({
        "query": {
            "read": "SecretItem",
            "select": ["id", "title", "secret_body", "secret_tag"],
            "filter": [{ "field": "secret_tag", "op": "eq", "value": plaintext_tag }]
        }
    });
    let read_res = spike_v6_transport::handle(&mut db, &facts, "/read", &read_query, &caller, wire).await;
    assert_eq!(read_res["ok"], true, "read failed: {read_res}");
    let rows = read_res["rows"].as_array().expect("rows array");
    assert_eq!(rows.len(), 1, "exactly 1 row read");
    let read_row = &rows[0];

    // Assert automatic decryption to original plaintext
    assert_eq!(read_row["id"], created_id);
    assert_eq!(read_row["title"], "Production Secret");
    assert_eq!(read_row["secret_body"], plaintext_body, "secret_body decrypted to plaintext");
    assert_eq!(read_row["secret_tag"], plaintext_tag, "secret_tag decrypted to plaintext");

    // Assert hidden columns are removed
    assert!(read_row.get("__aip_id").is_none(), "__aip_id hidden column must be removed from /read");
    assert!(read_row.get("__aip_scope").is_none(), "__aip_scope hidden column must be removed from /read");

    // 6. KEY ROTATION & IDEMPOTENCY REPLAY (RED / GREEN)
    // Rotate HMAC keys: fp2 becomes active, fp1 retained
    let rotated_crypto = test_crypto_v2_rotated();
    encryption::set_runtime_crypto(Some(rotated_crypto.clone()));

    // Green: Replaying identical request with the same key returns cached result with replayed: true
    let replay_res = spike_v6_transport::handle(&mut db, &facts, "/apply", &create_body, &caller, wire).await;
    assert_eq!(replay_res["ok"], true, "replay failed: {replay_res}");
    assert_eq!(replay_res["replayed"], true, "expected replayed: true after rotation");
    assert_eq!(replay_res["created"][0]["id"], created_id);

    // Red: Modified request with same key is rejected with WIRE.IDEMPOTENCY_MISMATCH
    let mut tampered_create_body = create_body.clone();
    tampered_create_body["request"]["atomic"][0]["values"]["secret_body"] = json!("different-tampered-secret");
    let mismatch_res = spike_v6_transport::handle(&mut db, &facts, "/apply", &tampered_create_body, &caller, wire).await;
    assert_eq!(mismatch_res["ok"], false);
    assert_eq!(mismatch_res["code"], "WIRE.IDEMPOTENCY_MISMATCH", "Tampered request must be rejected!");

    // Green: /status with identical request returns replayed result
    let status_req = json!({
        "key": idem_key,
        "request": create_body["request"]
    });
    let status_res = spike_v6_transport::handle(&mut db, &facts, "/status", &status_req, &caller, wire).await;
    assert_eq!(status_res["ok"], true, "status check failed: {status_res}");
    assert_eq!(status_res["replayed"], true);

    // Red: /status with tampered request is rejected with WIRE.IDEMPOTENCY_MISMATCH
    let tampered_status_req = json!({
        "key": idem_key,
        "request": tampered_create_body["request"]
    });
    let status_mismatch_res = spike_v6_transport::handle(&mut db, &facts, "/status", &tampered_status_req, &caller, wire).await;
    assert_eq!(status_mismatch_res["ok"], false);
    assert_eq!(status_mismatch_res["code"], "WIRE.IDEMPOTENCY_MISMATCH");

    // 7. TAMPERED CIPHERTEXT DETECTION (WIRE.ENCRYPTION_CORRUPTED)
    // Directly tamper ciphertext in DB with valid header but invalid AEAD payload
    db.batch_execute(&format!(
        "UPDATE {schema}.secret_item SET secret_body = 'v2:s:dek1:1:AAAAAAAAAAAAAAAA:AAAAAAAAAAAAAAAAAAAAAA==' WHERE id = {created_id}"
    ))
    .await
    .unwrap();

    let corrupted_read_res = spike_v6_transport::handle(&mut db, &facts, "/read", &read_query, &caller, wire).await;
    assert_eq!(corrupted_read_res["ok"], false);
    assert_eq!(corrupted_read_res["code"], "WIRE.ENCRYPTION_CORRUPTED", "Corrupted ciphertext must yield WIRE.ENCRYPTION_CORRUPTED");

    // 8. UNKNOWN KEY DETECTION (WIRE.ENCRYPTION_UNAVAILABLE)
    db.batch_execute(&format!(
        "UPDATE {schema}.secret_item SET secret_body = 'v2:s:dek999:999:AAAAAAAAAAAAAAAA:AAAAAAAAAAAAAAAAAAAAAA==' WHERE id = {created_id}"
    ))
    .await
    .unwrap();

    let unavail_read_res = spike_v6_transport::handle(&mut db, &facts, "/read", &read_query, &caller, wire).await;
    assert_eq!(unavail_read_res["ok"], false);
    assert_eq!(unavail_read_res["code"], "WIRE.ENCRYPTION_UNAVAILABLE", "Missing key must yield WIRE.ENCRYPTION_UNAVAILABLE");

    // 9. UNSUPPORTED QUERY GATES (WIRE.ENCRYPTED_FIELD_NOT_QUERYABLE)
    // Sort on encrypted field
    let sort_query = json!({
        "query": {
            "read": "SecretItem",
            "select": ["id", "title"],
            "sort": [{ "field": "secret_body", "dir": "asc" }]
        }
    });
    let sort_res = spike_v6_transport::handle(&mut db, &facts, "/read", &sort_query, &caller, wire).await;
    assert_eq!(sort_res["ok"], false);
    assert_eq!(sort_res["code"], "WIRE.ENCRYPTED_FIELD_NOT_QUERYABLE");

    // Non-eq filter on encrypted field
    let non_eq_query = json!({
        "query": {
            "read": "SecretItem",
            "select": ["id", "title"],
            "filter": [{ "field": "secret_body", "op": "like", "value": "%test%" }]
        }
    });
    let non_eq_res = spike_v6_transport::handle(&mut db, &facts, "/read", &non_eq_query, &caller, wire).await;
    assert_eq!(non_eq_res["ok"], false);
    assert_eq!(non_eq_res["code"], "WIRE.ENCRYPTED_FIELD_NOT_QUERYABLE");

    // Clean up
    encryption::set_runtime_crypto(None);
    db.batch_execute(&format!("DROP SCHEMA IF EXISTS {schema} CASCADE")).await.unwrap();
    conn_handle.abort();
}

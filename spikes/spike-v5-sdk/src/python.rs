//! Python caller bindings use the same public fingerprint and resource Id wire as TypeScript.
use serde_json::Value;
use spike_v2_read::id_wire::IdWire;
use std::fmt::Write;

/// A union that is evaluated when the module loads (type aliases, functional TypedDict fields). `A | B` between classes needs Python 3.10,
/// `Union[A, B]` and `Optional[A]` work on 3.9. Unions inside annotations stay `A | B`: `from __future__ import annotations` keeps those unevaluated.
fn union(members: &[String]) -> String {
    if members.len() == 1 {
        members[0].clone()
    } else {
        format!("Union[{}]", members.join(", "))
    }
}

fn snake(name: &str) -> String {
    let mut result = String::new();
    for (i, ch) in name.chars().enumerate() {
        if ch.is_uppercase() && i > 0 {
            result.push('_');
        }
        result.extend(ch.to_lowercase());
    }
    result
}

fn pascal(name: &str) -> String {
    let mut result = String::new();
    let mut capitalize_next = true;
    for ch in name.chars() {
        if ch == '_' || ch == '-' {
            capitalize_next = true;
        } else if capitalize_next {
            result.extend(ch.to_uppercase());
            capitalize_next = false;
        } else {
            result.push(ch);
        }
    }
    result
}

fn value_type(facts: &Value, ty: &str) -> String {
    let base = ty.trim_end_matches('?');
    let clean = if let Some((name, _)) = base.split_once('(') { name } else { base };
    let t = if let Some(resource) = clean.strip_prefix("Ref<").or_else(|| clean.strip_prefix("Id<")).and_then(|s| s.strip_suffix('>')) {
        if resource == "principal" {
            if facts.get("actorMode").and_then(Value::as_str) == Some("principal") || facts.get("actor").and_then(Value::as_str) == Some("principal")
            {
                "principalId".to_string()
            } else {
                panic!("unsupported reference to principal without principal actor: {ty}");
            }
        } else if facts.get("resources").and_then(Value::as_object).is_some_and(|r| r.contains_key(resource)) {
            format!("{resource}Id")
        } else {
            panic!("unsupported or unknown resource reference in type: {ty}");
        }
    } else if let Some(en) = clean.strip_prefix("Enum<").and_then(|s| s.strip_suffix('>')) {
        if let Some(variants) = facts.get("enums").and_then(|e| e.get(en)).and_then(Value::as_array) {
            format!("Literal[{}]", variants.iter().map(|v| v.to_string()).collect::<Vec<_>>().join(", "))
        } else {
            panic!("unknown enum: {en}");
        }
    } else {
        match clean {
            "Text" | "Email" | "Url" | "Time" | "Date" => "str".to_string(),
            "Int" => "int".to_string(),
            "Bool" => "bool".to_string(),
            d if d.starts_with("Decimal<") && d.ends_with('>') => "str".to_string(),
            _ => panic!("unsupported or unknown type: {ty}"),
        }
    };
    if ty.ends_with('?') {
        format!("Optional[{t}]")
    } else {
        t
    }
}

/// Apply input TypedDicts and checked-name helpers. Input optionality is independent of nullability.
/// Helpers delegate to the installed Python SDK, preserving key/recovery and server validation.
pub fn contract_module_python(facts: &Value, wire: IdWire) -> String {
    let mut s = String::from("# Generated by aip service gen --lang python. Do not edit.\nfrom __future__ import annotations\nimport sys\nfrom typing import TYPE_CHECKING, Any, Literal, NewType, NoReturn, Optional, TypedDict, Union\nfrom aip_sdk import Client\n\n# `NotRequired` is in `typing` from Python 3.11. Before that, type checkers read it from `typing_extensions` and the module needs no\n# extra package at runtime: the stand-in below keeps `NotRequired[T]` evaluable, so the keys are only checked statically there.\nif sys.version_info >= (3, 11):\n    from typing import NotRequired\nelif TYPE_CHECKING:\n    from typing_extensions import NotRequired\nelse:\n    class NotRequired:\n        def __class_getitem__(cls, item):\n            return item\n\n");
    if facts.get("operations").and_then(Value::as_object).is_some_and(|ops| !ops.is_empty()) {
        s.push_str("from typing import cast\nimport json as _json\nfrom aip_sdk import validate_operation_output\n\n");
    }
    writeln!(s, "CONTRACT_FINGERPRINT = {:?}\nID_WIRE = {:?}\n", super::contract_fingerprint_with_all_extensions(facts, wire), wire.label()).unwrap();
    s.push_str("JobState = Literal[\"QUEUED\", \"RUNNING\", \"CANCEL_REQUESTED\", \"SUCCEEDED\", \"FAILED\", \"CANCELLED\"]\n");
    s.push_str("JobRun = TypedDict(\"JobRun\", {\"id\": str, \"operation\": str, \"state\": JobState}, total=False)\n\n");
    let scalar = match wire {
        IdWire::SafeNumber => "int",
        _ => "str",
    };
    if facts.get("actorMode").and_then(Value::as_str) == Some("principal") || facts.get("actor").and_then(Value::as_str) == Some("principal") {
        writeln!(s, "principalId = NewType(\"principalId\", {scalar})").unwrap();
    }
    for res in facts["resources"].as_object().unwrap().keys() {
        let scalar = if spike_v2_read::id_wire::id_kind(facts, res) == "uuid" { "str" } else { scalar };
        writeln!(s, "{res}Id = NewType(\"{res}Id\", {scalar})").unwrap();
    }
    let mut all_read_results = Vec::new();
    let mut all_apply_inputs = Vec::new();
    for (res, rf) in facts["resources"].as_object().unwrap() {
        if let Some(select) = rf["exposeRead"]["select"].as_object() {
            let desc = super::read_descriptors(facts);
            let row = select
                .keys()
                .map(|name| {
                    let ty = rf["fields"][name]["ty"].as_str().or_else(|| rf["aggregates"][name]["ty"].as_str()).unwrap();
                    let mut py = value_type(facts, ty);
                    if desc[res]["fields"][name]["nullable"] == true && !ty.ends_with('?') {
                        py = format!("Optional[{py}]");
                    }
                    format!("{name:?}: {py}")
                })
                .collect::<Vec<_>>()
                .join(", ");
            writeln!(s, "{res}Row = TypedDict({:?}, {{{row}}}, total=False)", format!("{res}Row")).unwrap();
            writeln!(s, "{res}ReadResult = TypedDict({:?}, {{\"rows\": list[{res}Row]}})", format!("{res}ReadResult")).unwrap();
            writeln!(s, "\ndef read_{}(client: Client, query: dict) -> list[{res}Row]:\n    return client.read(query)\n", snake(res)).unwrap();
            all_read_results.push(format!("{res}ReadResult"));
        }
        for (action, ex) in rf["exposeApply"].as_object().into_iter().flatten() {
            let prefix = format!("{res}{}", action.chars().next().unwrap().to_uppercase().collect::<String>() + &action[1..]);
            let targets = ex["target"].as_array().unwrap();
            let mut target_types = vec![];
            if targets.iter().any(|v| v == "id") {
                writeln!(s, "\nclass {prefix}Ids(TypedDict):\n    ids: list[{res}Id]").unwrap();
                target_types.push(format!("{prefix}Ids"));
            }
            if targets.iter().any(|v| v == "where") {
                let mut filters = vec![];
                for name in rf["exposeRead"]["filter"].as_array().into_iter().flatten().filter_map(|v| v.as_str()?.strip_suffix(".eq")) {
                    let class = format!("{prefix}Filter_{}", snake(name));
                    writeln!(
                        s,
                        "\nclass {class}(TypedDict):\n    field: Literal[{name:?}]\n    op: Literal[\"eq\"]\n    value: {}",
                        value_type(facts, rf["fields"][name]["ty"].as_str().unwrap())
                    )
                    .unwrap();
                    filters.push(class);
                }
                writeln!(
                    s,
                    "\nclass {prefix}Where(TypedDict):\n    where: list[{}]",
                    if filters.is_empty() { "NoReturn".into() } else { filters.join(" | ") }
                )
                .unwrap();
                target_types.push(format!("{prefix}Where"));
            }
            let mut params = String::new();
            let mut body = String::new();
            let mut apply_fields = vec![format!("\"apply\": Literal[\"{res}.{action}\"]"), format!("\"target\": {}", union(&target_types))];
            for (declared, key, suffix, optional) in [("patch", "values", "Values", true), ("expect", "expect", "Expect", false)] {
                if let Some(fields) = rf["transitions"][action][declared].as_array() {
                    writeln!(s, "\n{prefix}{suffix} = TypedDict(\"{prefix}{suffix}\", {{").unwrap();
                    for name in fields.iter().filter_map(Value::as_str) {
                        let ty = value_type(facts, rf["fields"][name]["ty"].as_str().unwrap());
                        writeln!(s, "    {name:?}: {},", if optional { format!("NotRequired[{ty}]") } else { ty }).unwrap();
                    }
                    s.push_str("})\n");
                    write!(params, ", {key}: {prefix}{suffix}").unwrap();
                    write!(body, ", {key:?}: dict({key})").unwrap();
                    apply_fields.push(format!("{key:?}: NotRequired[{prefix}{suffix}]"));
                }
            }
            writeln!(s, "\n{prefix}ApplyInput = TypedDict(\"{prefix}ApplyInput\", {{\n    {}\n}})\n", apply_fields.join(",\n    ")).unwrap();
            all_apply_inputs.push(format!("{prefix}ApplyInput"));
            writeln!(s,"\ndef apply_{}_{}(client: Client, target: {}{params}, *, key: str | None = None) -> dict:\n    return client.apply({{\"apply\": \"{res}.{action}\", \"target\": dict(target){body}}}, key=key)\n",snake(res),snake(action),target_types.join(" | ")).unwrap();
        }
    }
    if let Some(views) = facts.get("views").and_then(Value::as_object) {
        for (view_name, vf) in views {
            if let Some(fields) = vf.get("fields").and_then(Value::as_object) {
                let row = fields
                    .iter()
                    .map(|(name, fdef)| {
                        let ty = fdef["ty"].as_str().unwrap_or("str");
                        let py = value_type(facts, ty);
                        format!("{name:?}: {py}")
                    })
                    .collect::<Vec<_>>()
                    .join(", ");
                writeln!(s, "{view_name}Row = TypedDict({:?}, {{{row}}}, total=False)", format!("{view_name}Row")).unwrap();
                writeln!(s, "{view_name}ReadResult = TypedDict({:?}, {{\"rows\": list[{view_name}Row]}})", format!("{view_name}ReadResult")).unwrap();
                all_read_results.push(format!("{view_name}ReadResult"));
            }
        }
    }
    writeln!(
        s,
        "\nReadResult = {}",
        if all_read_results.is_empty() { "TypedDict(\"ReadResult\", {\"rows\": list[dict]})".into() } else { union(&all_read_results) }
    )
    .unwrap();
    writeln!(s, "ApplyInput = {}\n", if all_apply_inputs.is_empty() { "dict".into() } else { union(&all_apply_inputs) }).unwrap();

    if let Some(operations) = facts.get("operations").and_then(Value::as_object).filter(|ops| !ops.is_empty()) {
        let outputs: Value = Value::Object(
            super::operation_descriptors(facts)
                .as_object()
                .unwrap()
                .iter()
                .map(|(name, descriptor)| (name.clone(), descriptor["output"].clone()))
                .collect(),
        );
        let encoded = serde_json::to_string(&outputs.to_string()).unwrap();
        writeln!(s, "OPERATION_OUTPUTS: dict[str, dict[str, dict[str, Any]]] = _json.loads({encoded})\n").unwrap();
        let mut op_inputs = Vec::new();
        let mut op_outputs = Vec::new();
        for (op_name, op_val) in operations {
            let prefix = pascal(op_name);
            writeln!(s, "{prefix}OperationInput = TypedDict(\"{prefix}OperationInput\", {{").unwrap();
            if let Some(inputs) = op_val["input"].as_array() {
                for field in inputs {
                    let fname = field[0].as_str().unwrap();
                    let fty = field[1].as_str().unwrap();
                    let py_ty = value_type(facts, fty);
                    let opt = fty.ends_with('?');
                    writeln!(s, "    {fname:?}: {},", if opt { format!("NotRequired[{py_ty}]") } else { py_ty }).unwrap();
                }
            }
            s.push_str("})\n");
            op_inputs.push(format!("{prefix}OperationInput"));

            writeln!(s, "\n{prefix}OperationOutput = TypedDict(\"{prefix}OperationOutput\", {{").unwrap();
            if let Some(outputs) = op_val["output"].as_array() {
                for field in outputs {
                    let fname = field[0].as_str().unwrap();
                    let fty = field[1].as_str().unwrap();
                    let py_ty = value_type(facts, fty);
                    writeln!(s, "    {fname:?}: {py_ty},").unwrap();
                }
            }
            s.push_str("})\n");
            op_outputs.push(format!("{prefix}OperationOutput"));

            writeln!(
                s,
                "\ndef call_{}(client: Client, input: {prefix}OperationInput) -> {prefix}OperationOutput:\n    output = client.operation({op_name:?}, dict(input))\n    return cast({prefix}OperationOutput, validate_operation_output(output, OPERATION_OUTPUTS[{op_name:?}], ID_WIRE))\n",
                snake(op_name)
            ).unwrap();
        }
        writeln!(s, "\nOperationInput = {}", if op_inputs.is_empty() { "dict".into() } else { union(&op_inputs) }).unwrap();
        writeln!(s, "OperationOutput = {}\n", if op_outputs.is_empty() { "dict".into() } else { union(&op_outputs) }).unwrap();
    }
    s
}
